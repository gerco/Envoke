//go:build ignore

// logo_gen.go downsamples the docs favicon into logo_data.go, which holds
// the 16x16 RGBA pixels used to draw the Envoke icon in the root help.
//
// Run with: go generate ./cmd/ee
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"image"
	"image/png"
	"log"
	"os"
)

const (
	src  = "../../docs/static/favicon-32x32.png"
	dst  = "logo_data.go"
	size = 16
)

func main() {
	f, err := os.Open(src)
	if err != nil {
		log.Fatal(err)
	}
	defer f.Close()
	img, err := png.Decode(f)
	if err != nil {
		log.Fatal(err)
	}
	b := img.Bounds()
	if b.Dx() != 2*size || b.Dy() != 2*size {
		log.Fatalf("%s: want %dx%d, got %dx%d", src, 2*size, 2*size, b.Dx(), b.Dy())
	}

	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by logo_gen.go from %s; DO NOT EDIT.\n\n", src)
	fmt.Fprintf(&buf, "package main\n\n")
	fmt.Fprintf(&buf, "// logoPixels is the Envoke icon as %dx%d non-premultiplied RGBA.\n", size, size)
	fmt.Fprintf(&buf, "var logoPixels = [%d][%d][4]uint8{\n", size, size)
	for y := 0; y < size; y++ {
		buf.WriteString("{")
		for x := 0; x < size; x++ {
			fmt.Fprintf(&buf, "{%d,%d,%d,%d},", box(img, b.Min, x, y)...)
		}
		buf.WriteString("},\n")
	}
	buf.WriteString("}\n")

	out, err := format.Source(buf.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(dst, out, 0o644); err != nil {
		log.Fatal(err)
	}
}

// box averages a 2x2 block of premultiplied pixels and returns it
// un-premultiplied as 8-bit RGBA.
func box(img image.Image, min image.Point, x, y int) []any {
	var r, g, bl, a uint32
	for dy := 0; dy < 2; dy++ {
		for dx := 0; dx < 2; dx++ {
			pr, pg, pb, pa := img.At(min.X+2*x+dx, min.Y+2*y+dy).RGBA()
			r, g, bl, a = r+pr, g+pg, bl+pb, a+pa
		}
	}
	if a == 0 {
		return []any{0, 0, 0, 0}
	}
	return []any{r * 255 / a, g * 255 / a, bl * 255 / a, a / 4 >> 8}
}
